  and not exists(select 1 from public.contratos_vigencias v where v.contrato_id=c.id and v.numero=2);

insert into public.atas_itens(contrato_id,cpl,sim,item,marca_modelo,qtde_contratada,valor_unit,vencimento,status_contrato,empresa,prazo_entrega,secao_id)
select c.id,s.cpl,s.siam,s.item,s.marca_modelo,s.qtde,s.valor_unit,s.vencimento,'VIGENTE',s.fornecedor,s.prazo,c.secao_id
from stg_ata_itens s join public.contratos c on c.tipo_instrumento='ATA' and upper(c.numero_contrato)=upper(s.siam)
where not exists(
  select 1 from public.atas_itens ai where ai.contrato_id=c.id and upper(btrim(ai.item))=upper(btrim(s.item))
    and upper(coalesce(btrim(ai.marca_modelo),''))=upper(coalesce(btrim(s.marca_modelo),''))
);

insert into public.atas_execucao(
  ata_item_id,emenda_id,emenda_item_id,cpl,sim,item,unidade,qtde,valor,empenho,data_af,prev_entrega,
  dt_entrega,nf,obs_prazo,origem_recurso,data_entrega_unidade,secao_id,possui_patrimonio
)
select ai.id,e.id,ei.id,s.cpl,s.siam,s.item,s.unidade,s.qtde,s.valor,s.empenho,s.data_af,s.prev_entrega,
       s.dt_entrega,s.nf,s.obs_prazo,s.origem_recurso,s.data_entrega_unidade,c.secao_id,s.possui_patrimonio
from stg_ata_execucoes s
join public.contratos c on c.tipo_instrumento='ATA' and upper(c.numero_contrato)=upper(s.siam)
join public.atas_itens ai on ai.contrato_id=c.id and upper(btrim(ai.item))=upper(btrim(s.item))
 and upper(coalesce(btrim(ai.marca_modelo),''))=upper(coalesce(btrim(s.marca_modelo),''))
left join stg_ata_emendas sm on sm.linha=s.linha
left join public.emendas e on sm.linha is not null and e.ano=2026 and upper(coalesce(e.tipo,''))='MUNICIPAL' and e.emenda=sm.emenda
left join public.emenda_itens ei on ei.emenda_id=e.id and upper(btrim(ei.item))=upper(btrim(sm.item_db))
 and coalesce(ei.qtde,ei.qtde_cadastrada,0)=sm.qtde and coalesce(ei.vl_total,ei.vl_total_cadastrado,0)=sm.vl_total
where not exists(select 1 from public.atas_execucao ae where split_part(ae.obs_prazo,' | ',1)='IMPORT-ATAS-XLSX29-L'||s.linha);

-- Mantém o item municipal de 2026 ligado ao processo e espelha os dados já comprovados.
update public.emenda_itens ei set
  processo_id=p.id,
  cpl=x.cpl,
  status='AF EMITIDA - AGUARDANDO ENTREGA/CONFIRMACAO',
  empenho=coalesce(x.empenho,ei.empenho),
  nota_fiscal=coalesce(x.nf,ei.nota_fiscal),
  patrimonio=coalesce(sm.patrimonio,ei.patrimonio),
  unidade_entrega=coalesce(sm.unidade_origem,ei.unidade_entrega),
  unidade_entrega_id=coalesce(u.id,ei.unidade_entrega_id,ei.unidade_beneficiada_id),
  data_entrega=coalesce(to_char(sm.data_entrega_unidade,'DD/MM/YYYY'),ei.data_entrega),
  data_atualizacao=to_char(current_date,'DD/MM/YYYY')
from stg_ata_emendas sm
join public.emendas e on e.ano=2026 and upper(coalesce(e.tipo,''))='MUNICIPAL' and e.emenda=sm.emenda
join stg_ata_execucoes x on x.linha=sm.linha
join public.processos p on upper(coalesce(p.tipo,''))='CPL' and regexp_replace(p.identificador,'\s','','g')=regexp_replace(regexp_replace(x.cpl,'^CPL\s*','','i'),'\s','','g')
left join public.unidades u on u.nome=sm.unidade_oficial
where ei.emenda_id=e.id and upper(btrim(ei.item))=upper(btrim(sm.item_db))
  and coalesce(ei.qtde,ei.qtde_cadastrada,0)=sm.qtde and coalesce(ei.vl_total,ei.vl_total_cadastrado,0)=sm.vl_total;

-- Empenhos simples; campos com mais de um número permanecem no texto da execução para saneamento.
insert into public.empenhos(numero,numero_normalizado,ano,processo_id,contrato_id,fornecedor_id,emenda_id,
  fonte_tipo,fonte_descricao,valor_empenhado,valor_anulado,saldo_empenho,status,origem_sistema,origem_codigo,observacoes,secao_id)
select ltrim((regexp_match(s.empenho,'^(0*[0-9]+)/([0-9]{4})$'))[1],'0'),
       ltrim((regexp_match(s.empenho,'^(0*[0-9]+)/([0-9]{4})$'))[1],'0'),
       (regexp_match(s.empenho,'^(0*[0-9]+)/([0-9]{4})$'))[2]::integer,
       c.processo_id,c.id,c.fornecedor_id,
       case when count(distinct ae.emenda_id) filter(where ae.emenda_id is not null)=1 then min(ae.emenda_id::text)::uuid else null end,
       case when bool_or(ae.origem_recurso='emenda') then 'EMENDA' else 'RECURSO PRÓPRIO' end,
       string_agg(distinct s.unidade,'; '),sum(s.valor),0,sum(s.valor),'emitido','importacao_planilha_atas_2026',
       'EMP-'||(regexp_match(s.empenho,'^(0*[0-9]+)/([0-9]{4})$'))[2]||'-'||ltrim((regexp_match(s.empenho,'^(0*[0-9]+)/([0-9]{4})$'))[1],'0'),
       'Data de emissão não disponível na planilha; valor corresponde às execuções vinculadas.',c.secao_id
from stg_ata_execucoes s
join public.contratos c on c.tipo_instrumento='ATA' and upper(c.numero_contrato)=upper(s.siam)
join public.atas_execucao ae on split_part(ae.obs_prazo,' | ',1)='IMPORT-ATAS-XLSX29-L'||s.linha
where s.empenho ~ '^0*[0-9]+/[0-9]{4}$'
group by s.empenho,c.processo_id,c.id,c.fornecedor_id,c.secao_id
having not exists(select 1 from public.empenhos ep
  where ep.numero=ltrim((regexp_match(s.empenho,'^(0*[0-9]+)/([0-9]{4})$'))[1],'0')
    and ep.ano=(regexp_match(s.empenho,'^(0*[0-9]+)/([0-9]{4})$'))[2]::integer);

insert into public.empenho_itens(empenho_id,item_id,emenda_id,emenda_item_id,quantidade_vinculada,valor_vinculado,exec_id,observacoes,secao_id)
select ep.id,null,ae.emenda_id,ae.emenda_item_id,s.qtde,s.valor,ae.id,'Importação histórica — linha '||s.linha,c.secao_id
from stg_ata_execucoes s
join public.contratos c on c.tipo_instrumento='ATA' and upper(c.numero_contrato)=upper(s.siam)
join public.atas_execucao ae on split_part(ae.obs_prazo,' | ',1)='IMPORT-ATAS-XLSX29-L'||s.linha
join public.empenhos ep on ep.numero=ltrim((regexp_match(s.empenho,'^(0*[0-9]+)/([0-9]{4})$'))[1],'0')
 and ep.ano=(regexp_match(s.empenho,'^(0*[0-9]+)/([0-9]{4})$'))[2]::integer
where s.empenho ~ '^0*[0-9]+/[0-9]{4}$'
  and not exists(select 1 from public.empenho_itens eii where eii.empenho_id=ep.id and eii.exec_id=ae.id);

-- NF somente quando há número único e data de recebimento. NF sem data continua pendente no Controle de Entregas.
insert into public.notas_fiscais(numero,numero_normalizado,fornecedor_id,contrato_id,processo_id,emenda_id,
  data_recebimento,valor_total,valor_bruto,status,origem_sistema,origem_codigo,observacoes,secao_id)
select 'NF '||s.nf,regexp_replace(s.nf,'\D','','g'),c.fornecedor_id,c.id,c.processo_id,
       case when count(distinct ae.emenda_id) filter(where ae.emenda_id is not null)=1 then min(ae.emenda_id::text)::uuid else null end,
       max(s.dt_entrega::date),sum(s.valor),sum(s.valor),'recebida','importacao_planilha_atas_2026',
       'NF-'||c.id||'-'||regexp_replace(s.nf,'\D','','g'),'Data de emissão e arquivo não disponíveis na planilha.',c.secao_id
from stg_ata_execucoes s
join public.contratos c on c.tipo_instrumento='ATA' and upper(c.numero_contrato)=upper(s.siam)
join public.atas_execucao ae on split_part(ae.obs_prazo,' | ',1)='IMPORT-ATAS-XLSX29-L'||s.linha
where s.nf ~ '^\s*[0-9]+\s*$' and s.dt_entrega is not null
group by s.nf,c.fornecedor_id,c.id,c.processo_id,c.secao_id
having not exists(select 1 from public.notas_fiscais nf where nf.contrato_id=c.id and nf.numero_normalizado=regexp_replace(s.nf,'\D','','g'));

insert into public.nota_fiscal_itens(nota_fiscal_id,item_id,emenda_id,emenda_item_id,empenho_id,
  quantidade,valor_unitario,valor_total,observacoes,secao_id)
select nf.id,null,ae.emenda_id,ae.emenda_item_id,ep.id,s.qtde,s.valor/nullif(s.qtde,0),s.valor,
       'Importação histórica — linha '||s.linha,c.secao_id
from stg_ata_execucoes s
join public.contratos c on c.tipo_instrumento='ATA' and upper(c.numero_contrato)=upper(s.siam)
join public.atas_execucao ae on split_part(ae.obs_prazo,' | ',1)='IMPORT-ATAS-XLSX29-L'||s.linha
join public.notas_fiscais nf on nf.contrato_id=c.id and nf.numero_normalizado=regexp_replace(s.nf,'\D','','g')
left join public.empenhos ep on ep.numero=ltrim((regexp_match(s.empenho,'^(0*[0-9]+)/([0-9]{4})$'))[1],'0')
 and ep.ano=(regexp_match(s.empenho,'^(0*[0-9]+)/([0-9]{4})$'))[2]::integer
where s.nf ~ '^\s*[0-9]+\s*$' and s.dt_entrega is not null
  and not exists(select 1 from public.nota_fiscal_itens nfi where nfi.nota_fiscal_id=nf.id and nfi.observacoes='Importação histórica — linha '||s.linha);

insert into public.atas_execucao_unidades(exec_id,ata_item_id,emenda_item_id,unidade_seq,patrimonio,numero_serie,
  nota_fiscal_id,recebido_em,recebido_por,obs,secao_id)
select ae.id,ae.ata_item_id,ae.emenda_item_id,u.seq,u.patrimonio,null,nf.id,u.recebido_em,null,
       'Importação histórica da planilha física de emendas 2026',ae.secao_id
from stg_ata_unidades u
join stg_ata_execucoes s on s.linha=u.linha
join public.atas_execucao ae on split_part(ae.obs_prazo,' | ',1)='IMPORT-ATAS-XLSX29-L'||u.linha
join public.atas_itens ai on ai.id=ae.ata_item_id
join public.contratos c on c.id=ai.contrato_id
left join public.notas_fiscais nf on nf.contrato_id=c.id and nf.numero_normalizado=regexp_replace(s.nf,'\D','','g')
where not exists(select 1 from public.atas_execucao_unidades x where x.exec_id=ae.id and x.unidade_seq=u.seq);

-- Travas de consistência: qualquer falha aborta toda a carga.
do $$
declare v integer;
begin
  select count(*) into v from public.contratos where tipo_instrumento='ATA' and numero_contrato in (select siam from stg_ata_instrumentos);
  if v <> 18 then raise exception 'Esperadas 18 atas, encontradas %',v; end if;
  select count(*) into v from public.atas_itens ai join public.contratos c on c.id=ai.contrato_id where c.numero_contrato in (select siam from stg_ata_instrumentos);
  if v <> 36 then raise exception 'Esperados 36 itens de ata, encontrados %',v; end if;
  select count(*) into v from public.atas_execucao where obs_prazo like 'IMPORT-ATAS-XLSX29-L%';
  if v <> 312 then raise exception 'Esperadas 312 execuções, encontradas %',v; end if;
  select count(*) into v from public.atas_execucao where obs_prazo like 'IMPORT-ATAS-XLSX29-L%' and emenda_item_id is not null;
  if v <> 58 then raise exception 'Esperadas 58 execuções municipais 2026 vinculadas, encontradas %',v; end if;
  select count(*) into v from public.atas_execucao_unidades ae where ae.obs='Importação histórica da planilha física de emendas 2026';
  if v <> 110 then raise exception 'Esperadas 110 unidades físicas, encontradas %',v; end if;
end $$;
