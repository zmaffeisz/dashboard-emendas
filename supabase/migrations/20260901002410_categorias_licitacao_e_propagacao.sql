-- Mantem a ordem das colunas existentes e acrescenta a categoria ao final.
create or replace view public.vw_processos_resumo
with (security_invoker = true)
as
select p.id,
       p.identificador,
       p.tipo,
       p.natureza,
       p.objeto,
       p.modalidade,
       p.status,
       p.secao,
       p.valor_estimado,
       p.observacao,
       p.gera_mais_contratos,
       p.created_at,
       count(i.id)::integer as total_itens,
       coalesce(sum(i.qtde), 0::numeric) as total_qtde,
       coalesce(sum(coalesce(i.valor_contratado, i.valor_estimado, 0::numeric) * coalesce(i.qtde, 1::numeric)), 0::numeric) as total_itens_valor,
       p.tipo_servico,
       p.servico_mensal_itens,
       p.servico_mensal_meses,
       p.servico_mensal_valor_mensal,
       p.servico_mensal_valor_global,
       (select count(*)::integer from public.contratos c where c.processo_id = p.id) as n_contratos,
       p.servico_demanda_meses,
       p.sc,
       p.secao_id,
       p.servico_trimestral_itens,
       p.servico_trimestral_meses,
       p.servico_trimestral_ciclos,
       p.servico_trimestral_valor_trimestral,
       p.servico_trimestral_valor_global,
       p.link_publico_sei,
       p.categoria_id,
       (select cl.nome from public.categorias_licitacao cl where cl.id = p.categoria_id) as categoria_licitacao
  from public.processos p
  left join public.itens i on i.processo_id = p.id
 group by p.id;

comment on column public.processos.categoria_id is 'Categoria mestre escolhida na abertura da licitacao.';
comment on column public.itens.categoria_id is 'Categoria herdada do processo de licitacao.';
comment on column public.contratos.categoria_id is 'Categoria herdada do processo de origem.';
comment on column public.atas_itens.categoria_id is 'Categoria herdada do contrato/ata de origem.';
