create or replace function private.herdar_categoria_licitacao()
returns trigger
language plpgsql
set search_path = pg_catalog, public, private
as $$
declare
  v_categoria_id bigint;
begin
  if tg_table_name = 'itens' and new.processo_id is not null then
    select p.categoria_id into v_categoria_id
      from public.processos p where p.id = new.processo_id;
    new.categoria_id := v_categoria_id;
  elsif tg_table_name = 'contratos' and new.processo_id is not null then
    select p.categoria_id into v_categoria_id
      from public.processos p where p.id = new.processo_id;
    new.categoria_id := v_categoria_id;
  elsif tg_table_name = 'atas_itens' and new.contrato_id is not null then
    select c.categoria_id into v_categoria_id
      from public.contratos c where c.id = new.contrato_id;
    new.categoria_id := v_categoria_id;
  end if;
  return new;
end;
$$;

create or replace function private.propagar_categoria_licitacao()
returns trigger
language plpgsql
set search_path = pg_catalog, public, private
as $$
begin
  if tg_table_name = 'processos' then
    update public.itens
       set categoria_id = new.categoria_id
     where processo_id = new.id
       and categoria_id is distinct from new.categoria_id;
    update public.contratos
       set categoria_id = new.categoria_id
     where processo_id = new.id
       and categoria_id is distinct from new.categoria_id;
  elsif tg_table_name = 'contratos' then
    update public.atas_itens
       set categoria_id = new.categoria_id
     where contrato_id = new.id
       and categoria_id is distinct from new.categoria_id;
  end if;
  return null;
end;
$$;

revoke all on function private.herdar_categoria_licitacao() from public, anon, authenticated;
revoke all on function private.propagar_categoria_licitacao() from public, anon, authenticated;

drop trigger if exists trg_itens_herdar_categoria_licitacao on public.itens;
create trigger trg_itens_herdar_categoria_licitacao
before insert or update of processo_id on public.itens
for each row execute function private.herdar_categoria_licitacao();

drop trigger if exists trg_contratos_herdar_categoria_licitacao on public.contratos;
create trigger trg_contratos_herdar_categoria_licitacao
before insert or update of processo_id on public.contratos
for each row execute function private.herdar_categoria_licitacao();

drop trigger if exists trg_atas_itens_herdar_categoria_licitacao on public.atas_itens;
create trigger trg_atas_itens_herdar_categoria_licitacao
before insert or update of contrato_id on public.atas_itens
for each row execute function private.herdar_categoria_licitacao();

drop trigger if exists trg_processos_propagar_categoria_licitacao on public.processos;
