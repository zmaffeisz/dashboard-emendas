   set categoria_id = p.categoria_id
  from public.processos p
 where p.id = c.processo_id
   and c.categoria_id is distinct from p.categoria_id;

update public.atas_itens ai
   set categoria_id = c.categoria_id
  from public.contratos c
 where c.id = ai.contrato_id
   and ai.categoria_id is distinct from c.categoria_id;

