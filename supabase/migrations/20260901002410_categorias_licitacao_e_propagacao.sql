after update of categoria_id on public.processos
for each row
when (old.categoria_id is distinct from new.categoria_id)
execute function private.propagar_categoria_licitacao();

drop trigger if exists trg_contratos_propagar_categoria_licitacao on public.contratos;
create trigger trg_contratos_propagar_categoria_licitacao
after update of categoria_id on public.contratos
for each row
when (old.categoria_id is distinct from new.categoria_id)
execute function private.propagar_categoria_licitacao();

