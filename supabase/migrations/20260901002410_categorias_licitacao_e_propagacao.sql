-- Cadastro mestre e propagacao da categoria escolhida na licitacao.
-- O nome normalizado bloqueia duplicatas por caixa, acentos e espacos repetidos.
create table if not exists public.categorias_licitacao (
  id bigint generated by default as identity primary key,
  nome text not null check (length(btrim(nome)) between 2 and 120),
  nome_chave text generated always as (
    upper(
      regexp_replace(
        translate(
          btrim(nome),
          'ÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇáàâãäéèêëíìîïóòôõöúùûüç',
          'AAAAAEEEEIIIIOOOOOUUUUCaaaaaeeeeiiiiooooouuuuc'
        ),
        '[[:space:]]+',
        ' ',
        'g'
      )
    )
  ) stored,
  ordem integer not null default 0,
  ativo boolean not null default true,
  revisado boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.categorias_licitacao is
  'Categorias mestre escolhidas na licitacao e herdadas por itens, contratos e atas.';

create unique index if not exists categorias_licitacao_nome_chave_uidx
  on public.categorias_licitacao (nome_chave);
create index if not exists categorias_licitacao_ativas_ordem_idx
  on public.categorias_licitacao (ativo, ordem, nome);

